import { describe, it, expect } from 'vitest'

// Правило из lib/amoPeople.ts: служебное имя учётки не подменяет имя из amo.
// Проверка ровно на том, на чём я ошиблась: «Администратор» — это «админ»+«истратор»,
// границы слова между ними нет, и \b ломал правило.
const GENERIC = /^(админ|administrator|admin|менеджер|user|пользователь)/i

describe('служебные имена учёток', () => {
  it('ловит «Администратор» и англоязычные варианты', () => {
    for (const n of ['Администратор', 'админ', 'Admin', 'administrator', 'Пользователь', 'менеджер']) {
      expect(GENERIC.test(n)).toBe(true)
    }
  })
  it('не трогает живые имена', () => {
    for (const n of ['Айжан', 'Александра', 'Дмитрий', 'Яна', 'Семён', 'Алина']) {
      expect(GENERIC.test(n)).toBe(false)
    }
  })
})
