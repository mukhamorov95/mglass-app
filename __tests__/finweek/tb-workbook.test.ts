// ФП Ф6: эталон — рабочая книга владельца «Фин_модели_и_расчета_ТБ_РАЗНЫЕ_ВИДЫ»
// (листы «ТБ1» и «ФМ ТБ2», ноябрь 2025, правка 11.11.2025). Движок приложения
// (lib/breakeven.ts) должен воспроизвести книгу по строкам.
import { describe, it, expect } from 'vitest'
import { analyzeBreakeven, type BreakevenModel } from '@/lib/breakeven'

const glass = { name: 'Доход от продажи стекла (Металл)', plan: 4_000_000, vars: [
  { name: 'Закуп сырья стекла и пр + расходные', pct: 31.33 },
  { name: 'Сдельная ЗП мастеров цеха', pct: 8.55 },
  { name: 'Сдельная ЗП менеджера ОП', pct: 1 },
  { name: 'Транспортные', pct: 1.3 },
  { name: 'Налоги НДС, н/прибыль', pct: 5.55 },
  { name: 'ГСМ', pct: 1.48 },
] }
const items = { name: 'Доход от продажи готовых изделий с монтажем (MGlass)', plan: 10_000_000, vars: [
  { name: 'Фурнитура и расходные', pct: 19.85 },
  { name: 'Сырьё стекло', pct: 21.2 },
  { name: 'Субподрядчики', pct: 4.53 },
  { name: 'Сдельная монтажники, конструктора, замерщики', pct: 18.19 },
  { name: 'Сдельная менеджеров ОП', pct: 2.5 },
  { name: 'Транспортные', pct: 1.3 },
  { name: 'ГСМ', pct: 1.48 },
  { name: 'Сдельная РОП', pct: 0 },
  { name: 'УСН', pct: 5 },
] }
const fx = (rows: [string, number][]) => rows.map(([name, amount]) => ({ name, amount, kind: 'fixed' as const }))

const TB1: BreakevenModel = {
  incomes: [glass, items], funds: { invest: 0, training: 0, reserve: 0, prodBonus: 0 }, ownerPct: 0, ownerRub: 0, overflowBonusPct: 0,
  fixed: fx([['Аренда помещения', 475_000], ['Ком расходы', 20_000], ['ЗП оклад', 800_000], ['Лизинг', 505_200], ['Кредит и проценты', 344_980],
    ['Налоги с ЗП', 181_000], ['Связь', 7_000], ['ПО', 20_000], ['Обслуживание авто', 10_000], ['Обслуживание оборудования', 10_000],
    ['Госпошлины, штрафы', 5_000], ['Инструмент', 5_000], ['Канц и хоз', 5_000], ['Банковская комиссия', 35_000], ['Реклама', 250_000],
    ['Рекламные подрядчики', 40_000], ['Аутсорс бухгалтерия', 135_000], ['Взносы ИП', 6_710], ['Уборка', 4_000], ['Вывоз мусора', 10_000]]),
}
const TB2: BreakevenModel = {
  ...TB1, funds: { invest: 14, training: 1.5, reserve: 5, prodBonus: 0 },
  fixed: fx([['Аренда помещения', 650_000], ['Ком расходы', 20_000], ['ЗП оклад', 920_000], ['Лизинг', 505_200], ['Кредит и проценты', 344_980],
    ['Налоги с ЗП', 231_000], ['Транспортный налог', 2_500], ['КАСКО, ОСАГО', 12_000], ['Связь', 7_000], ['ПО', 20_000], ['Обслуживание авто', 80_000],
    ['Обслуживание оборудования', 10_000], ['Госпошлины, штрафы', 10_000], ['Инструмент', 5_000], ['Канц и хоз', 10_000], ['Банковская комиссия', 75_000],
    ['Реклама', 313_035], ['Рекламные подрядчики', 40_000], ['Мероприятия, подарки', 20_000], ['Спецодежда', 5_000], ['Аутсорс бухгалтерия', 135_000],
    ['Взносы ИП', 6_710], ['Уборка', 4_000], ['Вывоз мусора', 10_000]]),
}
const R = (n: number) => Math.round(n)

describe('ТБ1 книги владельца — по строкам', () => {
  const a = analyzeBreakeven(TB1)
  it('строка 9: доход 14 000 000', () => expect(a.revenue).toBe(14_000_000))
  it('строки 25–26: переменные стекла 1 968 400 (49,21 %), маржа 2 031 600', () => {
    expect(R(a.perIncome[0].varRub)).toBe(1_968_400)
    expect(R(a.perIncome[0].margin)).toBe(2_031_600)
  })
  it('строки 37–38: переменные изделий 7 405 000 (74,05 %), маржа 2 595 000', () => {
    expect(R(a.perIncome[1].varRub)).toBe(7_405_000)
    expect(R(a.perIncome[1].margin)).toBe(2_595_000)
  })
  it('строка 45: маржинальная прибыль 4 626 600', () => expect(R(a.margin)).toBe(4_626_600))
  it('строка 77: постоянные 2 868 890', () => expect(a.fixed).toBe(2_868_890))
  it('строка 78: прибыль 1 757 710; строка 10: расходы 12 242 290', () => {
    expect(R(a.remainder)).toBe(1_757_710)
    expect(R(a.revenue - a.remainder)).toBe(12_242_290)
  })
  it('ТБ = постоянные / доля маржи', () => expect(a.tb1).toBe(R(2_868_890 / (4_626_600 / 14_000_000))))
})

describe('ФМ ТБ2 книги владельца — по строкам', () => {
  const a = analyzeBreakeven(TB2)
  it('строки 46–49: фонды из маржи 647 724 + 69 399 + 231 330 = 948 453 (20,5 % маржи)', () => {
    expect(R(4_626_600 * 0.14)).toBe(647_724)
    expect(R(a.fundsRub)).toBe(948_453)
  })
  it('строка 50: после фондов 3 678 147', () => expect(R(a.distributable)).toBe(3_678_147))
  it('строка 77: постоянные 3 436 425', () => expect(a.fixed).toBe(3_436_425))
  it('строка 78: прибыль 241 722; строка 9: расходы 13 758 278', () => {
    expect(R(a.remainder)).toBe(241_722)
    expect(R(a.revenue - a.remainder)).toBe(13_758_278)
  })
  it('ТБ с фондами = постоянные / (доля маржи × (1 − 20,5 %))', () =>
    expect(a.tb1).toBe(R(3_436_425 / ((4_626_600 / 14_000_000) * (1 - 0.205)))))
})

describe('ТБ при нулевой или отрицательной марже', () => {
  it('числа нет — вместо него причина на экране', () => {
    const a = analyzeBreakeven({ ...TB1, incomes: [{ ...glass, vars: [{ name: 'всё', pct: 100 }] }] })
    expect(a.marginPct).toBe(0)
    expect(a.tb1).toBeNull()
  })
})

import { whyNoBreakeven } from '@/lib/breakeven'
describe('whyNoBreakeven — причина вместо прочерка', () => {
  it('маржа ноль', () => expect(whyNoBreakeven({ revenue: 1, marginPct: 0 })).toMatch(/забирают всю выручку/))
  it('фонды 100 % маржи', () => expect(whyNoBreakeven({ revenue: 1, marginPct: 0.3 }, 1)).toMatch(/забирают 100 % маржи/))
  it('нет плана', () => expect(whyNoBreakeven({ revenue: 0, marginPct: 0 })).toMatch(/Нет плана/))
  it('точка есть — причины нет', () => expect(whyNoBreakeven({ revenue: 1, marginPct: 0.3 }, 0.2)).toBeNull())
})
