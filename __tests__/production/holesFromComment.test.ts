import { describe, it, expect } from 'vitest'
import { holesFromComment } from '@/lib/production/holes'

// Строки взяты из боевых комментариев b2b_orders.items за июль–сентябрь 2026.
describe('диаметры из комментария — отдаём как есть', () => {
  it('берёт кусок с диаметрами и счётчик, отбрасывая метку позиции', () => {
    const c = 'Стекло 1 (поз.2) · Кромки полировать, фаска 1,5х45°. Отверстия Ø16, Ø10, Ø16, Ø10 + Ø48 · отв: 5'
    expect(holesFromComment(c)).toBe('Кромки полировать, фаска 1,5х45°. Отверстия Ø16, Ø10, Ø16, Ø10 + Ø48 · отв: 5')
  })

  it('не выдумывает: нет диаметров — пустая строка', () => {
    expect(holesFromComment('Стекло 1 (поз.1) · Кромки полировать')).toBe('')
    expect(holesFromComment('')).toBe('')
    expect(holesFromComment(null)).toBe('')
    expect(holesFromComment(undefined)).toBe('')
  })

  it('неоднозначные записи проходят нетронутыми — их читает человек, а не парсер', () => {
    // «Ø18/19» — неопределённость диаметра, не количество.
    expect(holesFromComment('Отверстия Ø18/19; привязки 1250, 45, 27'))
      .toBe('Отверстия Ø18/19; привязки 1250, 45, 27')
    // «два ряда по 4» — восемь штук прописью.
    expect(holesFromComment('Ø22, два ряда по 4, нижний ряд на 100 мм от низа'))
      .toBe('Ø22, два ряда по 4, нижний ряд на 100 мм от низа')
    // Количество перед диаметром.
    expect(holesFromComment('4 отв. Ø16 + 2 отв. Ø10 вверху, 1 отв. Ø48 внизу'))
      .toBe('4 отв. Ø16 + 2 отв. Ø10 вверху, 1 отв. Ø48 внизу')
  })

  it('«отв: N» без диаметров всё равно полезен — это счётчик от разбора', () => {
    expect(holesFromComment('Стекло 2 (поз.3) · отв: 2')).toBe('отв: 2')
  })

  it('одиночная Ø без цифры — не диаметр, не берём', () => {
    expect(holesFromComment('Стекло · кромка Ø полировка')).toBe('')
  })

  it('вырезы сами по себе не отверстия', () => {
    expect(holesFromComment('Стекло 1 (поз.1) · вырезы: 3')).toBe('')
  })
})

describe('второй знак диаметра — ∅, а не только Ø', () => {
  // 35 боевых позиций написаны через Ø (U+00D8), 30 — через ∅ (U+2205).
  // Первая версия ловила только Ø и теряла почти половину, включая все позиции Айжана.
  it('ловит ∅ (знак пустого множества) наравне с Ø', () => {
    expect(holesFromComment('Ст3 · закалённое, пк; отв. ∅16 (2 отв.) и ∅10 · отв: 3'))
      .toBe('закалённое, пк; отв. ∅16 (2 отв.) и ∅10 · отв: 3')
  })

  it('ловит вариант со строчной ø и с Φ', () => {
    expect(holesFromComment('Ст1 · 2 отв. ø10')).toBe('2 отв. ø10')
    expect(holesFromComment('Ст1 · 2 отв. Φ10')).toBe('2 отв. Φ10')
  })

  it('знак без цифры диаметром не считается', () => {
    expect(holesFromComment('Ст1 · множество ∅ пустое')).toBe('')
  })
})
