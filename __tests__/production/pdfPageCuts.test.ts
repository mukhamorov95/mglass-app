import { describe, expect, it } from 'vitest'
import { pageCuts } from '@/lib/pdfCapture'

describe('pageCuts: нарезка листа на страницы', () => {
  it('короткий лист — одна страница, даже если после последнего блока есть хвост', () => {
    expect(pageCuts(1002, 2000, [300, 1000])).toEqual([1002])
  })

  it('режет по низу последнего блока, который влез, а не посреди строки', () => {
    expect(pageCuts(2500, 1000, [400, 800, 1200, 1900, 2500])).toEqual([800, 1200, 1900, 2500])
  })

  it('блок выше страницы режется по границе страницы, цикл не зависает', () => {
    expect(pageCuts(2500, 1000, [2500])).toEqual([1000, 2000, 2500])
  })

  it('пустой лист не даёт страниц', () => {
    expect(pageCuts(0, 1000, [])).toEqual([])
  })
})
