// Число из поля ввода конструктора: пробелы, «%» и «₽» отбрасываются, запятая — десятичный знак.
// Раньше запятая выбрасывалась, и «35,5» читалось как 355 (маржа ×10, скидка «5,5» → 55 %).
export const numOr = (v: string) => {
  const n = Number(String(v ?? '').replace(/[^\d.,-]/g, '').replace(',', '.'))
  return isFinite(n) ? n : 0
}
