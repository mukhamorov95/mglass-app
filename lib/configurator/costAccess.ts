// Кто видит себестоимость комплекта в ответе конфигуратора.
//
// Правило проекта: себестоимость не покидает внутренний контур. Публичный
// виджет и /api/configurator/* отдают анониму только сумму «от N ₽». Раньше
// развилка стояла на наличии сессии, а не на роли — и партнёр, у которого
// сессия есть, получал glassCost, hardwareCost, marginPct и строки комплекта.
//
// Список ролей держим здесь, отдельно от маршрута: его расширение должно быть
// осознанным действием, видимым в диффе и в тестах.
const COST_ROLES = new Set(['admin', 'ceo', 'manager', 'commercial', 'cfo'])

export function canSeeKitCost(role: string | null | undefined): boolean {
  return !!role && COST_ROLES.has(role)
}
