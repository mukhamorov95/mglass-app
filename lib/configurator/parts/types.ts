// Паспорт детали фурнитуры: данные, а не код. Одна деталь = один файл в catalog/.
// Всё в МИЛЛИМЕТРАХ — как на чертеже поставщика; в метры переводит только рендер.
//
// Зачем данные, а не React-компонент на каждую деталь: форму и посадку тогда можно
// проверить тестом, показать на стенде и сверить с чертежом числом, а не глазами.
// Ошибка в одном паспорте выключает одну деталь, а не ломает сцену.

export type V3 = [number, number, number]

// ── Геометрия ───────────────────────────────────────────────────────────────
// Набор намеренно маленький: всё, что есть в душевой фурнитуре, собирается из
// коробки, цилиндра, шара, обоймы и кольца. Больше примитивов — больше способов
// нарисовать одно и то же по-разному.
export type Prim =
  // прямоугольное тело; round — радиус скругления рёбер (0 = острые)
  | { p: 'box'; size: V3; at?: V3; rot?: V3; round?: number }
  // цилиндр/конус вдоль оси; d2 — диаметр второго торца (по умолчанию = d)
  | { p: 'cyl'; d: number; d2?: number; len: number; axis?: 'x' | 'y' | 'z'; at?: V3; rot?: V3 }
  | { p: 'ball'; d: number; at?: V3 }
  // обойма вокруг трубы сечением section (внешний габарит = сечение + 2×wall)
  | { p: 'clamp'; section: [number, number]; wall: number; len: number; axis?: 'x' | 'y' | 'z'; at?: V3 }
  // кольцо/шайба (тор): d — средний диаметр, thk — толщина прутка
  | { p: 'ring'; d: number; thk: number; axis?: 'x' | 'y' | 'z'; at?: V3 }

// ── Посадка ─────────────────────────────────────────────────────────────────
// На что деталь садится. Сцена отдаёт ПОВЕРХНОСТЬ, деталь — как она к ней крепится.
// Раньше это считалось арифметикой прямо в месте установки — там и жили ошибки
// (ручка получала смещение по X и НОЛЬ по Z: высота верная, посадка мимо стекла).
export type MountOn =
  | 'glass-face'   // плоскость полотна (ручки, кнобы, чаши купе)
  | 'glass-edge'   // торец полотна (петли, зажимы, держатели)
  | 'tube'         // обхватывает штангу поперёк (держатели, каретки)
  | 'tube-end'     // надевается на торец штанги (заглушки, стыки к стене)
  | 'wall'         // фланцем в стену
  | 'free'         // ничем не связана — координаты задаёт сцена (соединители)

export type Mount = {
  on: MountOn
  standoff?: number       // мм по нормали от поверхности до нуля детали
  along?: number          // мм вдоль поверхности (вправо по +X локальной рамки)
  lift?: number           // мм по вертикали от заданной точки
  through?: boolean       // сквозная: зеркальная половина с другой стороны стекла
  clamps?: [number, number] // какое сечение штанги обхватывает (проверяется тестом)
  glassMm?: [number, number] // на какую толщину стекла рассчитана
}

// ── Паспорт ─────────────────────────────────────────────────────────────────
export type PartSpec = {
  id: string                 // ключ формы; попадает в SHAPE_LIST и в поле «вид» справочника
  article: string            // артикул поставщика — как в прайсе
  label: string              // человеческое название
  role: string               // роль комплекта (kit.RoleId): hinge | handle | mount-wall | …
  supplier?: { name: string; url?: string }
  // Откуда взяты числа. Без этого через месяц не проверить, чертёж это или глазомер.
  source?: { drawing?: string; photos?: string[]; note?: string }
  dims: Record<string, number>  // числа с чертежа, мм — на них ссылается geometry
  geometry: Prim[]
  mount: Mount
  // Готовая модель вместо параметрики (запасной путь, если поставщик даст файл).
  gltf?: string
}

export type PartIssue = { id: string; field: string; problem: string }
