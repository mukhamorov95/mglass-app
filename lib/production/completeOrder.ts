// «Всё готово» — закрыть заказ целиком одним действием (запрос Никиты, 27.08).
//
// Никита стоит на упаковке, то есть в конце маршрута. Чтобы отметить один заказ, он делал
// четыре действия: найти → раскрыть → «Открыть карточку заказа» → отметить. Отметка должна
// стоить одно нажатие там, где он уже стоит.
//
// ─── Атрибуция: решение и почему именно такое ────────────────────────────────
// Опасность очевидна: если Никита закрывает заказ целиком, а резку физически делал Бекмурза
// и не отметил, — резка запишется на Никиту. Выработка (П16) и «Кто что делал» начнут врать
// ровно там, где мы только что научились говорить правду.
//
// Ничего нового изобретать не нужно: механизм уже построен в П1. Когда рабочий закрывает этап,
// cascadePriorStages закрывает все предыдущие этапы этой детали с auto_closed = true и БЕЗ
// исполнителя — потому что их физически никто не отмечал.
//
// Поэтому «Всё готово» закрывает НЕ все задачи подряд, а по одной на деталь — последнюю
// открытую в её маршруте. Её и записываем на нажавшего: именно её завершение он утверждает,
// стоя над готовым изделием. Всё, что до неё, закрывает каскад — без исполнителя.
//
// Правило одной строкой: ЧЕЛОВЕКУ ЗАПИСЫВАЕТСЯ ТОЛЬКО ТО, ЧТО ОН УТВЕРЖДАЕТ САМ;
// всё, что система вывела за него, остаётся без исполнителя.
//
// Побочно это чинит и старую кнопку «Упаковано разом» в /production-app/orders: она слала
// по запросу на КАЖДУЮ незакрытую задачу (на заказе в 61 задачу — 61 запрос подряд),
// и каждая писалась на нажавшего.
//
// Чистая логика — ни Supabase, ни React.

export type ClosableTask = {
  id:             number
  item_index:     number
  sequence_order: number
  status:         string
}

// По одной задаче на деталь — последняя открытая в маршруте.
// Каскад закроет всё, что до неё, поэтому больше ничего слать не нужно.
export function pickFinalTasks(tasks: ClosableTask[]): ClosableTask[] {
  const byItem = new Map<number, ClosableTask>()
  for (const t of tasks) {
    if (t.status === 'done') continue
    const cur = byItem.get(t.item_index)
    if (!cur || t.sequence_order > cur.sequence_order) byItem.set(t.item_index, t)
  }
  return [...byItem.values()].sort((a, b) => a.item_index - b.item_index)
}

// Сколько задач реально закроется — для подписи на кнопке. Показывать число
// закрываемых задач, а не деталей: одно касание на 61 задачу человек должен видеть заранее.
export function countClosable(tasks: ClosableTask[]): number {
  return tasks.filter(t => t.status !== 'done').length
}

// ─── Почему у мастера по найденному заказу пусто ─────────────────────────────
// Владелец нашёл заказ по поиску, увидел «0 дет. · ✓ 2 сделано» и написал
// «изменений не вижу». Код отработал верно — у него по этому заказу задач нет, —
// но карточка молчала. Рабочий в такой ситуации решает, что заказ потерялся, и
// идёт искать обходной путь: именно так Никита и нашёл «Открыть карточку заказа».
//
// Три исхода, и третий важнее первого: человек должен понимать, что заказ жив,
// просто не у него. Пока состав работы не загружен — говорим только то, что знаем
// наверняка, и ничего не достраиваем.

export type EmptyReason = 'unknown' | 'order-done' | 'elsewhere'

export function explainEmptyQueue(opts: {
  myOpen: number
  workLoaded: boolean
  orderOpen: number
}): EmptyReason | null {
  if (opts.myOpen > 0) return null           // у мастера есть работа — объяснять нечего
  if (!opts.workLoaded) return 'unknown'     // не знаем — не выдумываем
  return opts.orderOpen === 0 ? 'order-done' : 'elsewhere'
}
