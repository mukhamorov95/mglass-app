// Списание материала в момент закрытия РЕЗКИ (решение владельца 27.08.2026,
// 05-РЕШЕНИЯ/2026-08-27-списание-материала-в-момент-резки.md).
//
// Раньше списывали на упаковке. Замер показал, почему это неверно: резка — самый живой
// этап цеха (834 живых отметки против 337 у упаковки), до упаковки доходит треть задач,
// и материал физически расходуется именно на резке.
//
// ─── Почему решает отдельный модуль, а не условие на месте ───────────────────
// Закрыть резку можно ТРЕМЯ путями: очередь цеха (api/production-tasks/[id]), карточка
// заказа и QR-экран (api/b2b-orders/[id]/sync-stages), «Всё готово»
// (api/production/complete-order). Плюс каскад, который закрывать умеет, а списывать
// не должен. Условие, размноженное по трём файлам, разъедется — это уже было со счётчиком
// «Всё готово», который считал не то же, что делал сервер.
//
// ─── Каскадная резка ТОЖЕ списывает — исправлено 27.08 ───────────────────────
// Сначала здесь стояло обратное: каскад не списывает, «он закрывает этапы, которых физически
// не делали». Это была ошибка, и моя. Каскад утверждает ровно противоположное — см. его
// собственный комментарий: «отметка этапа = все предыдущие этапы этой детали физически УЖЕ
// СДЕЛАНЫ: нельзя закалить нерезаное и упаковать несверлёное».
//
// Мы перенесли на материал правило из П1 (каскад не даёт исполнителя), не проверив посылку.
// Она другая: «неизвестно, КТО сделал» и «неизвестно, БЫЛО ли сделано» — разные утверждения.
// Каскад говорит первое. Для выработки это запрет приписывать человеку, для материала —
// не запрет списывать: лист вскрыт.
//
// Цена ошибки была измерима: 48 заказов без единой живой отметки резки, 7 из них уже
// упакованы — по ним материал не списался бы никогда. И доля росла бы: после #351 рабочий
// закрывает свой этап, не дожидаясь предыдущего, а «Всё готово» закрывает остальное каскадом.
//
// Чистая логика — ни Supabase, ни React.

export const CUTTING_STAGE = 'cutting'

// Откуда пришла отметка. Каскад присутствует в перечислении сознательно: он должен быть
// назван и явно отвергнут, а не забыт.
// 'my-stage' — «Готово на моей станции»: рабочий закрывает свой этап по всем
// деталям заказа. Отметка живая, имя пишется — работу он утверждает сам.
export type MarkSource = 'worker' | 'order-card' | 'complete-order' | 'my-stage' | 'cascade'

export type CuttingMark = {
  orderId:   number
  itemIndex: number
  stageKey:  string
  source:    MarkSource
  /** production_tasks.rework_count на момент отметки. 0 — деталь режут впервые. */
  attempt:   number
}

export type ConsumeIntent = {
  orderId:   number
  itemIndex: number
  /** Ключ идемпотентности на стороне склада — (заказ, позиция, попытка). */
  attempt:   number
}

// Материал списывает любое закрытие резки, включая каскадное: физика одна и та же.
export function shouldConsume(mark: CuttingMark): boolean {
  return mark.stageKey === CUTTING_STAGE
}

// А вот ИМЯ приписывается только живой отметке. Каскад закрывает то, что никто не отмечал,
// и подставлять туда нажавшего значит соврать в выработке (П16) и в «Кто что делал».
// Склад допускает пустой by — движение будет без автора, и это честно.
export function isAttributable(source: MarkSource): boolean {
  return source !== 'cascade'
}

// Что отдать складу по пачке отметок. Дубли по (позиция, попытка) схлопываются:
// «Всё готово» может прислать несколько отметок одной детали за один запрос.
export function planConsume(marks: CuttingMark[]): ConsumeIntent[] {
  const seen = new Set<string>()
  const out: ConsumeIntent[] = []
  for (const m of marks) {
    if (!shouldConsume(m)) continue
    const key = `${m.orderId}:${m.itemIndex}:${m.attempt}`
    if (seen.has(key)) continue
    seen.add(key)
    out.push({ orderId: m.orderId, itemIndex: m.itemIndex, attempt: m.attempt })
  }
  return out
}

// ─── Отмена отметки: два разных случая, два разных последствия ───────────────
// Отмена этапа (мисклик, «отметили не тот заказ») — материал НЕ расходовался, нужно
// встречное движение: иначе ошибка молча уводит остаток, и потом никто не поймёт, отчего
// цифра неверна. Для склада «неверно и непонятно почему» хуже, чем «данных нет».
// «Переделать» — материал израсходован, откат не нужен: дальше спишется следующая попытка
// (attempt вырос), и это физически верно — взяли новый лист.
export type ReopenReason = 'unset' | 'rework'

// Откат привязан к ПЕРЕОТКРЫТИЮ ЗАДАЧИ РЕЗКИ, а не к тому, какой этап сняли руками.
// Причина: снять могут упаковку, а каскад при её ошибочной отметке закрыл и резку — значит
// откатывать надо по факту переоткрытия резки, чем бы оно ни было вызвано. Иначе мисклик по
// позднему этапу уводит материал безвозвратно.
export function shouldReverse(reopened: { stageKey: string; reason: ReopenReason }): boolean {
  return reopened.stageKey === CUTTING_STAGE && reopened.reason === 'unset'
}
