// Как сотрудник записан в книгах владельца («Продажи Мгласс», «Аналитика дохода»).
// В users.name стоят «Семен», «Дмитрий», «Администратор», а в книгах — «Семён»,
// «Дима», «Влад». Фильтр «только свои» по точному имени отдавал Семёну и
// Дмитрию пустые экраны, хотя строки с их именем в базе есть.

const ALIASES: Record<string, string[]> = {
  'семен': ['Семён', 'Семен'],
  'дмитрий': ['Дима', 'Дмитрий'],
  'дима': ['Дима', 'Дмитрий'],
  'администратор': ['Влад'],
  'владислав': ['Влад'],
  'влад': ['Влад'],
  'саша': ['Александра'],
  'александра': ['Александра'],
}

const key = (s: string) => s.trim().toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ')

export function bookNames(userName: string): string[] {
  const name = userName.trim()
  if (!name) return []
  return [...new Set([name, ...(ALIASES[key(name)] ?? [])])]
}
