function parseJson(text) {
  const m = text.match(/\{[\s\S]*\}/)
  if (!m) return null
  try { return JSON.parse(m[0]) } catch { return null }
}

export const MODEL = OPUS

// Запрос собирается одной функцией для обычного и пакетного режима: иначе промпт или
// лимит токенов в двух местах разойдутся, и пакет разберёт архив не тем, что проверяли.
export function buildParams(image, mime = 'image/jpeg') {
  return {
    model: MODEL,
    max_tokens: 700,
    messages: [{
      role: 'user',
      content: [
        { type: 'image', source: { type: 'base64', media_type: mime, data: image.toString('base64') } },
        { type: 'text', text: PROMPT },
      ],
    }],
  }
}

// calls — по ним считается цена. batch: true — вызов из пакета, он стоит вдвое дешевле.
export function parseMessage(message, { batch = false } = {}) {
  const text = message.content.map(c => (c.type === 'text' ? c.text : '')).join('')
  const out = parseJson(text)
  if (!out) return null
  out.model = message.model
  out.calls = [{ model: message.model, in: message.usage.input_tokens, out: message.usage.output_tokens, batch }]
  return out
}

export async function classifyFrame(image, mime = 'image/jpeg', client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })) {
  const message = await client.messages.create(buildParams(image, mime))
  return parseMessage(message)
}

const cap = s => s.charAt(0).toUpperCase() + s.slice(1)

// Куда кадр ложится в дереве на Яндекс.Диске. Порядок веток — как просил владелец:
// сначала изделие, потом тип открывания, потом геометрия и трек.
export function folderFor(c) {
  if (!c) return '05 Прочее/Не разобрано'
  if ((c.blockers ?? []).length > 0) return '99 Не для публикации'
  // Чертежи и скриншоты не должны разбавлять папки с объектами: их ищут не там и не за тем
  if (c.kind && c.kind !== 'фото') return '05 Прочее/Чертежи и скриншоты'

  if (c.product === 'душевая') {
    const s = c.shower
    if (!s || s.opening === 'не видно')   return '01 Душевые/Тип не определён'
    if (s.opening === 'без двери')        return '01 Душевые/Без двери (walk-in)'
    if (s.opening === 'шторка на ванну')  return '01 Душевые/Шторка на ванну'
    const g = !s.geometry || s.geometry === 'не видно' ? 'Геометрия не видна' : cap(s.geometry)
    if (s.opening === 'распашная')        return `01 Душевые/Распашные/${g}`
    const t = !s.track || s.track === 'не видно' ? 'Трек не видно' : `${cap(s.track)} трек`
    return `01 Душевые/Раздвижные/${g}/${t}`
  }

  if (c.product === 'зеркало') {
    const m = c.mirror ?? {}
    if (m.light === 'с подсветкой')  return '02 Зеркала/С подсветкой'
    if (m.light === 'без подсветки') return m.frame === 'в раме' ? '02 Зеркала/В раме' : '02 Зеркала/Без подсветки'
    return '02 Зеркала/Тип не определён'
  }

  if (c.product === 'перегородка') return '03 Перегородки и лофт'
  if (c.product === 'ограждение')  return '04 Ограждения'
  return '05 Прочее'
}
