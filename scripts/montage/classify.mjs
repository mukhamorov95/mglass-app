import Anthropic from '@anthropic-ai/sdk'

// Разбор кадра из «Монтажей». Основную массу тянет Haiku — кадров тысячи, и разница
// в цене на таком объёме решает. Opus подключается только там, где Haiku сам сказал,
// что не уверен: спорных обычно единицы процентов.
export const HAIKU = 'claude-haiku-4-5-20251001'
export const OPUS  = 'claude-opus-5'

// «Не видно» — полноправный ответ, а не отговорка. Трек на готовом кадре виден не всегда,
// и папка «Трек не видно» честнее, чем угаданный «закрытый» в общей куче.
export const PROMPT = `Ты разбираешь фотографию с монтажа изделий из стекла (душевые, зеркала, перегородки, ограждения).
Кадры снимают монтажники на телефон в квартирах на стадии ремонта — коробки, пыль, стремянки в кадре это норма.

Верни ТОЛЬКО JSON без пояснений:
{
  "kind": "фото|чертёж или схема|скриншот",
  "product": "душевая|зеркало|перегородка|ограждение|другое|не изделие",
  "shower": {"opening":"раздвижная|распашная|без двери|шторка на ванну|не видно",
             "geometry":"прямая|угловая, одна дверь|угловая, две двери|в нишу|П-образная|не видно",
             "track":"открытый|закрытый|не видно"},
  "mirror": {"light":"с подсветкой|без подсветки|не видно","frame":"в раме|без рамы|не видно"},
  "stage": "готово|в процессе|до монтажа|упаковка или доставка|цех",
  "blockers": ["люди","документы","деньги","адрес или табличка"],
  "marketing": 0,
  "confidence": 0.0,
  "note": "одна короткая фраза, что на кадре"
}

Как отвечать:
- "kind": "чертёж или схема" — если это рисунок, эскиз, чертёж с выносками и подписями деталей,
  а не снимок реального помещения. Такой кадр всё равно разбирай по остальным полям.
- Различай душевую и перегородку по назначению, а не по форме:
  стекло вокруг поддона, трапа или ванны, в санузле, рядом с лейкой или смесителем — это ДУШЕВАЯ,
  даже если полотно одно и похоже на простую перегородку.
  Перегородка — это зонирование комнаты: лофт-перегородка, межкомнатная дверь-стена,
  стекло между кухней и гостиной, стеклянный кабинет. В санузле перегородок не бывает.
- "shower" заполняй только если product = "душевая", "mirror" — только если "зеркало".
- Раздвижная — дверь едет по верхней штанге или треку. Распашная — на петлях. Без двери — одно стекло (walk-in).
- Открытый трек: ролики и штанга видны снаружи. Закрытый: механизм спрятан в профиль-короб.
- Геометрия: прямая — одно полотно по фронту; угловая — два полотна сходятся в угол,
  тогда различай одну дверь или две; в нишу — стекло между двух стен; П-образная — три стороны.
- Если деталь не видна на кадре — ставь "не видно". Не угадывай.
- "blockers": лица людей, любые документы и бумаги с текстом, деньги, таблички с адресом
  или номером квартиры. Пустой массив, если ничего этого нет.
- "marketing": 0 — служебный кадр (стройка, мусор, крупный план крепежа без контекста),
  5 — готовый чистый интерьер, который не стыдно поставить на сайт.
- "confidence" — насколько уверен в product и типе: 0.0–1.0.`

function parseJson(text) {
  const m = text.match(/\{[\s\S]*\}/)
  if (!m) return null
  try { return JSON.parse(m[0]) } catch { return null }
}

async function ask(client, model, image, mime) {
  const res = await client.messages.create({
    model,
    max_tokens: 700,
    messages: [{
      role: 'user',
      content: [
        { type: 'image', source: { type: 'base64', media_type: mime, data: image.toString('base64') } },
        { type: 'text', text: PROMPT },
      ],
    }],
  })
  const text = res.content.map(c => (c.type === 'text' ? c.text : '')).join('')
  const out = parseJson(text)
  if (out) {
    out.model = model
    out.usage = { in: res.usage.input_tokens, out: res.usage.output_tokens }
  }
  return out
}

export async function classifyFrame(image, mime = 'image/jpeg', client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })) {
  const first = await ask(client, HAIKU, image, mime)
  if (!first) return null

  // Спорное переспрашиваем моделью посильнее. Порог подобран так, чтобы на Opus
  // уходили единицы процентов — иначе теряется вся экономия.
  if ((first.confidence ?? 0) >= 0.75) return first
  const second = await ask(client, OPUS, image, mime)
  if (!second) return first
  second.escalated = true
  second.usage = { ...second.usage, haiku: first.usage }
  return second
}

const cap = s => s.charAt(0).toUpperCase() + s.slice(1)

// Куда кадр ложится в дереве на Яндекс.Диске. Порядок веток — как просил владелец:
// сначала изделие, потом тип открывания, потом геометрия и трек.
export function folderFor(c) {
  if (!c) return '05 Прочее/Не разобрано'
  if ((c.blockers ?? []).length > 0) return '99 Не для публикации'
  // Чертежи и скриншоты не должны разбавлять папки с объектами: их ищут не там и не за тем
  if (c.kind && c.kind !== 'фото') return '05 Прочее/Чертежи и скриншоты'

  if (c.product === 'душевая') {
    const s = c.shower
    if (!s || s.opening === 'не видно')   return '01 Душевые/Тип не определён'
    if (s.opening === 'без двери')        return '01 Душевые/Без двери (walk-in)'
    if (s.opening === 'шторка на ванну')  return '01 Душевые/Шторка на ванну'
    const g = !s.geometry || s.geometry === 'не видно' ? 'Геометрия не видна' : cap(s.geometry)
    if (s.opening === 'распашная')        return `01 Душевые/Распашные/${g}`
    const t = !s.track || s.track === 'не видно' ? 'Трек не видно' : `${cap(s.track)} трек`
    return `01 Душевые/Раздвижные/${g}/${t}`
  }

  if (c.product === 'зеркало') {
    const m = c.mirror ?? {}
    if (m.light === 'с подсветкой')  return '02 Зеркала/С подсветкой'
    if (m.light === 'без подсветки') return m.frame === 'в раме' ? '02 Зеркала/В раме' : '02 Зеркала/Без подсветки'
    return '02 Зеркала/Тип не определён'
  }

  if (c.product === 'перегородка') return '03 Перегородки и лофт'
  if (c.product === 'ограждение')  return '04 Ограждения'
  return '05 Прочее'
}
