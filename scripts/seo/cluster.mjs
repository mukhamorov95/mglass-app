import fs from 'node:fs'
import { pathToFileURL } from 'node:url'

// Группировка вопросов по намерению, а не по словам: один вопрос ≠ одна статья.
// Люди спрашивают одно и то же разными словами, и на кластер пишется один текст.
// Порядок важен — вопрос попадает в первый подошедший кластер, поэтому узкие выше широких.
export const CLUSTERS = [
  { key: 'Не наше: декор и самоделки', re: /оплест|макраме|ротанг|задекорир|декорир|оформить|вырезать|в домашних условиях|состарить|покрасить рам/ },
  { key: 'Зачем это нужно',         re: /^зачем|^для чего|^нужно ли|^стоит ли|^можно ли/ },
  { key: 'Управление и сенсор',     re: /включить|выключить|настроить|сенсор|управл|не работает|перестал/ },
  { key: 'Где купить и заказать',    re: /^где |где купить|где заказать|где можно заказ|заказать зеркало|на заказ где/ },
  { key: 'Подключение и электрика', re: /подключ|розетк|провод|электричеств|выключател|питани|батарейк|аккумулятор|замыкан|ток\b|заземл/ },
  { key: 'Размеры и высота',        re: /размер|высот|диаметр|ширин|какого размера|на какой высоте|сколько см|габарит/ },
  { key: 'Монтаж и крепление',      re: /повесить|вешать|закрепить|крепить|установ|приклеить|клей|плитк|гипсокартон|кафел|стен[уые]|дюбел|скотч|держ|сверл|монтаж|снять/ },
  { key: 'Выбор: какое брать',      re: /^(как[оиа][ейя]|какие|какой|чем отлича|что лучше|в чем разниц|в чём разниц)|лучше|выбрать|отлича|разниц|плюсы|минусы|стоит ли/ },
  { key: 'Цена и сроки',            re: /сколько стоит|цена|стоимост|дорого|дешев|за сколько|сроки|сколько времени|сколько делает/ },
  { key: 'Уход и запотевание',      re: /запотева|антизапот|мыть|мою|чистит|протира|уход|налет|налёт|разводы|потеет|туман/ },
  { key: 'Как это устроено',        re: /как называ|что такое|как работает|как устроен|как делают|как производ|из чего|фацет|амальгам|триплекс|led|светодиод/ },
  { key: 'Свет и яркость',          re: /яркост|теплый свет|тёплый свет|холодн|нейтральн|кельвин|4000|подсветка какая|цвет свечения|диммер|регулир/ },
  { key: 'Безопасность и влага',    re: /влагостойк|ванной можно|безопасн|ip\d|влажн|бьется|бьётся|осколк|закален/ },
]

export function clusterOf(q) {
  for (const c of CLUSTERS) if (c.re.test(q)) return c.key
  return 'Прочее'
}

// argv[1] пуст при `node -e` и при импорте из другого модуля — без проверки
// pathToFileURL бросает, и модуль нельзя даже импортировать.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const csv = fs.readFileSync(process.argv[2], 'utf8').replace(/^﻿/, '')
  const rows = csv.split('\n').slice(1).filter(Boolean).map(l => l.split(';'))
  const questions = rows.filter(r => r[2] === 'да').map(r => ({ q: r[0], seed: r[1] }))

  const by = new Map()
  for (const { q, seed } of questions) {
    const k = clusterOf(q)
    if (!by.has(k)) by.set(k, [])
    by.get(k).push({ q, seed })
  }
  const order = [...by.entries()].sort((a, b) => b[1].length - a[1].length)
  for (const [k, list] of order) {
    console.log(`\n## ${k} — ${list.length} вопросов`)
    const seeds = [...new Set(list.map(x => x.seed))]
    console.log(`   темы: ${seeds.join(', ')}`)
    for (const x of list.slice(0, 8)) console.log(`   • ${x.q}`)
    if (list.length > 8) console.log(`   …ещё ${list.length - 8}`)
  }
  console.log(`\nвсего вопросов: ${questions.length}, кластеров: ${by.size}`)
}
