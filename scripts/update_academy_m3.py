"""Update Academy Module 3 'Продукты MGlass' content via Supabase REST API."""

import json
import os
import ssl
import urllib.request
import urllib.error

SUPABASE_URL = os.environ.get("NEXT_PUBLIC_SUPABASE_URL", "https://qbypyrzkguwlelyjehbj.supabase.co")
SERVICE_KEY = os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "")

HEADERS = {
    "apikey": SERVICE_KEY,
    "Authorization": f"Bearer {SERVICE_KEY}",
    "Content-Type": "application/json",
}

CTX = ssl._create_unverified_context()


def patch(table, record_id, data):
    url = f"{SUPABASE_URL}/rest/v1/{table}?id=eq.{record_id}"
    body = json.dumps(data, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(url, data=body, headers={**HEADERS, "Prefer": "return=minimal"}, method="PATCH")
    try:
        with urllib.request.urlopen(req, context=CTX) as resp:
            print(f"  OK  PATCH {table} id={record_id}: {resp.status}")
    except urllib.error.HTTPError as e:
        print(f"  ERR PATCH {table} id={record_id}: {e.status} {e.read().decode()}")


def post(table, data):
    url = f"{SUPABASE_URL}/rest/v1/{table}"
    body = json.dumps(data, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(url, data=body, headers={**HEADERS, "Prefer": "return=representation"}, method="POST")
    try:
        with urllib.request.urlopen(req, context=CTX) as resp:
            result = json.loads(resp.read().decode())
            new_id = result[0]["id"] if result else "?"
            print(f"  OK  POST {table}: new_id={new_id}")
            return new_id
    except urllib.error.HTTPError as e:
        print(f"  ERR POST {table}: {e.status} {e.read().decode()}")
        return None


