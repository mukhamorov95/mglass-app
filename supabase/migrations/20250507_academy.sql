CREATE TABLE IF NOT EXISTS academy_modules (
  id          SERIAL PRIMARY KEY,
  level       INT  NOT NULL CHECK (level BETWEEN 1 AND 5),
  title       TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  icon        TEXT DEFAULT '📚',
  sort_order  INT  DEFAULT 0,
  active      BOOLEAN DEFAULT true,
  created_at  TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academy_lessons (
  id           SERIAL PRIMARY KEY,
  module_id    INT  REFERENCES academy_modules(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  content      TEXT NOT NULL,
  lesson_type  TEXT NOT NULL DEFAULT 'article', -- article | video | checklist
  video_url    TEXT,
  duration_min INT  DEFAULT 5,
  sort_order   INT  DEFAULT 0,
  active       BOOLEAN DEFAULT true,
  created_at   TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academy_quiz_questions (
  id            SERIAL PRIMARY KEY,
  module_id     INT  REFERENCES academy_modules(id) ON DELETE CASCADE,
  question      TEXT    NOT NULL,
  options       TEXT[]  NOT NULL,
  correct_index INT     NOT NULL,
  explanation   TEXT,
  sort_order    INT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS academy_user_progress (
  id           SERIAL PRIMARY KEY,
  user_id      UUID REFERENCES users(id) ON DELETE CASCADE,
  lesson_id    INT  REFERENCES academy_lessons(id) ON DELETE CASCADE,
  completed_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS academy_quiz_attempts (
  id         SERIAL PRIMARY KEY,
  user_id    UUID REFERENCES users(id) ON DELETE CASCADE,
  module_id  INT  REFERENCES academy_modules(id) ON DELETE CASCADE,
  score      INT  NOT NULL,
  total      INT  NOT NULL,
  passed     BOOLEAN NOT NULL,
  answers    JSONB,
  created_at TIMESTAMPTZ DEFAULT now()
);

