-- ─── Таблицы ──────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS academy_modules (
  id          SERIAL PRIMARY KEY,
  level       INT NOT NULL DEFAULT 1,
  title       TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  icon        TEXT NOT NULL DEFAULT '📚',
  sort_order  INT NOT NULL DEFAULT 0,
  active      BOOLEAN NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academy_lessons (
  id           SERIAL PRIMARY KEY,
  module_id    INT NOT NULL REFERENCES academy_modules(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  content      TEXT NOT NULL DEFAULT '',
  lesson_type  TEXT NOT NULL DEFAULT 'article',
  video_url    TEXT,
  duration_min INT NOT NULL DEFAULT 5,
  sort_order   INT NOT NULL DEFAULT 0,
  active       BOOLEAN NOT NULL DEFAULT true,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academy_quiz_questions (
  id            SERIAL PRIMARY KEY,
  module_id     INT NOT NULL REFERENCES academy_modules(id) ON DELETE CASCADE,
  question      TEXT NOT NULL,
  options       JSONB NOT NULL DEFAULT '[]',
  correct_index INT NOT NULL DEFAULT 0,
  explanation   TEXT,
  sort_order    INT NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academy_user_progress (
  id         SERIAL PRIMARY KEY,
  user_id    UUID NOT NULL,
  lesson_id  INT NOT NULL REFERENCES academy_lessons(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(user_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS academy_quiz_attempts (
  id         SERIAL PRIMARY KEY,
  user_id    UUID NOT NULL,
  module_id  INT NOT NULL REFERENCES academy_modules(id) ON DELETE CASCADE,
  score      INT NOT NULL DEFAULT 0,
  total      INT NOT NULL DEFAULT 0,
  passed     BOOLEAN NOT NULL DEFAULT false,
  answers    JSONB NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

