ON CONFLICT (id) DO NOTHING;

ALTER TABLE public.commercial_proposals ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "cp read own or all" ON public.commercial_proposals;
CREATE POLICY "cp read own or all" ON public.commercial_proposals
  FOR SELECT TO authenticated USING (
    manager_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.id = auth.uid()
        AND (u.role IN ('admin','ceo','commercial') OR u.see_all_orders = true)
    )
  );

DROP POLICY IF EXISTS "cp insert own" ON public.commercial_proposals;
CREATE POLICY "cp insert own" ON public.commercial_proposals
  FOR INSERT TO authenticated WITH CHECK ( manager_id = auth.uid() );

DROP POLICY IF EXISTS "cp update own or admin" ON public.commercial_proposals;
CREATE POLICY "cp update own or admin" ON public.commercial_proposals
  FOR UPDATE TO authenticated USING (
    manager_id = auth.uid()
    OR EXISTS (SELECT 1 FROM public.users u WHERE u.id = auth.uid() AND u.role IN ('admin','ceo'))
  );
