-- Внутренняя (передаточная) надбавка цеха для продаж самому M-Glass.
-- Мировая практика вертикально интегрированных производств (transfer pricing,
-- cost-plus): внутрь группы изделие передаётся по «себестоимость + 5-15%»,
-- полная производственная маржа берётся ТОЛЬКО с внешних B2B-клиентов —
-- иначе розница M-Glass задваивает маржу и цена клиенту неконкурентна.
-- Код имеет fallback 10% — колонка лишь делает процент настраиваемым.

alter table pricing_model_config_v2
  add column if not exists transfer_uplift_percent numeric not null default 10;
