-- Подтверждение погрузки: заказ в рейсе по умолчанию НЕ загружен. У машины
-- мастер отмечает «Загружен» по факту; при отправке рейса незагруженные
-- автоматически возвращаются в пул «заказы к отправке». Безопасно: забыл
-- отметить — заказ не уедет по ошибке. Обратная совместимость: старые связки
-- получают loaded=false, поэтому у уже отправленных партий поведение прежнее
-- (там вес/сумма уже зафиксированы в delivery_shipments).
alter table delivery_shipment_orders add column if not exists loaded boolean not null default false;
