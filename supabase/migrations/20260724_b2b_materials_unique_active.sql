-- Защита от дублей материалов в B2B-калькуляторе.
-- Причина бага: автосинк glass_price_matrix → b2b_materials мог отработать
-- дважды подряд (после сохранения цены), и оба чтения existing не видели
-- вставку друг друга → две активные строки на один материал → задвоение в
-- выпадающем списке калькулятора.
--
-- Частичный уникальный индекс: только ОДНА активная строка на
-- (name, category, thickness). Неактивные (исторические/скрытые) дубли
-- допускаются — на их id могут ссылаться старые заказы. Синк вставляет только
-- active=true, поэтому гонка теперь ловится здесь (23505), а не плодит дубль.
--
-- Перед применением зачищены существующие активные дубли (лишние → active=false).
CREATE UNIQUE INDEX IF NOT EXISTS b2b_materials_active_uniq
  ON b2b_materials (name, category, thickness)
  WHERE active;
