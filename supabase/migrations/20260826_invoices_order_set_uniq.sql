-- Счёт становится записью: печать счёта регистрирует его в invoices идемпотентно.
--
-- Ключ идемпотентности — НАБОР заказов, а не номер (менеджер номер правит).
-- Один набор order_ids = один действующий счёт. Индекс отбивает гонку двух
-- печатей: канонизируем набор (сортировка + уникальность) в приложении, здесь —
-- уникальность строкового представления среди неотменённых счетов.
--
-- Отменённый счёт (status='cancelled') из индекса исключён: после отмены тот же
-- набор заказов можно перевыставить.
--
-- Данных в invoices сейчас 0 — конфликтов при создании индекса не будет.

CREATE UNIQUE INDEX IF NOT EXISTS invoices_order_set_uniq
  ON public.invoices ( (array_to_string(order_ids, ',')) )
  WHERE status <> 'cancelled';
