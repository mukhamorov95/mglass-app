-- Счёт становится записью: печать счёта регистрирует его в invoices идемпотентно.
--
-- Ключ идемпотентности — НАБОР заказов, а не номер (менеджер номер правит).
-- Один набор order_ids = один действующий счёт. Индекс отбивает гонку двух
-- печатей: канонизацию набора (сортировка + уникальность) делает приложение
-- (lib/b2b/invoiceRegistry.canonicalOrderIds) ПЕРЕД записью.
--
-- Индексируем сам массив order_ids напрямую: btree сравнивает массивы структурно.
-- ВАЖНО: НЕ через array_to_string(order_ids, ',') — эта функция STABLE, а в
-- индексное выражение берутся только IMMUTABLE (иначе Postgres: 42P17). Первая
-- версия миграции на array_to_string не применялась вовсе — защиты не было; в
-- бою исправлено индексом по массиву (invoices_order_set_uniq_fix), этот файл
-- приведён к тому же виду, чтобы билд с нуля не упирался в ту же ошибку.
--
-- Отменённый счёт (status='cancelled') из индекса исключён: тот же набор заказов
-- можно перевыставить после отмены.

CREATE UNIQUE INDEX IF NOT EXISTS invoices_order_set_uniq
  ON public.invoices (order_ids)
  WHERE status <> 'cancelled';
