-- Признак происхождения движения расхода: «по факту» (человек подтвердил
-- количество) против «по плану» (автосписание при закрытии заказа списало
-- зарезервированное, факт никто не вводил).
--
-- Зачем: автосписание как побочный эффект «Готово» снимает трение с цеха, но
-- подменяет факт планом. Без пометки остаток снова станет фикцией — красивой и
-- незаметной. С пометкой инвентаризация показывает расхождение план↔факт как
-- реальную величину, а «сколько уходит сверх нормы» становится видимой цифрой.
--
-- Ось origin ОРТОГОНАЛЬНА reason (order/production/writeoff/…): reason — что за
-- операция, origin — на чём основано её количество. Поэтому отдельная колонка, а
-- не разбухание enum reason.

ALTER TABLE public.inventory_moves
  ADD COLUMN IF NOT EXISTS origin text NOT NULL DEFAULT 'fact'
  CHECK (origin IN ('fact','plan'));

-- Все существующие движения — по факту (ручной ввод, приход, инвентаризация,
-- начальные остатки). DEFAULT 'fact' проставит их автоматически.
COMMENT ON COLUMN public.inventory_moves.origin IS
  'fact — количество подтверждено человеком; plan — автосписание по резерву без ввода факта';

CREATE INDEX IF NOT EXISTS inventory_moves_origin_idx
  ON public.inventory_moves (origin) WHERE origin = 'plan';
