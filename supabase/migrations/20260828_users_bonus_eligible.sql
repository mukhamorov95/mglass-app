-- Участие в бонусном фонде цеха назначает владелец, а не формула по стажу.
-- (ПРИМЕНЕНА 28.08.2026)
--
-- Было: eligible = стаж >= 2 лет. Владелец назвал реальный состав фонда —
-- Сергей, Бекмурза, Адилет, Никита — и он из стажа не выводится: у Никиты 1.8 года,
-- у Адилета даты приёма нет вовсе. Правило, расходящееся с решением владельца,
-- будет расходиться и дальше: состав меняется по договорённостям, а не по календарю.
--
-- Стаж остаётся на экране справкой: он объясняет решение, но не принимает его.

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS bonus_eligible boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.users.bonus_eligible IS
  'Участвует в бонусном фонде цеха — назначает владелец в /admin/users';
